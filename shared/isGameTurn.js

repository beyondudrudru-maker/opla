/**
 * shared/isGameTurn.js
 *
 * PURPOSE
 *   Single source of truth for "is this a game-domain turn." Used by both
 *   decisionPipeline.js (to decide whether to skip memory/emotion machinery)
 *   and gemini.js (to decide whether to use the lean tactical persona).
 */

const { INTENTS } = require('../classifier/intentClassifier');

const GAME_KEYWORD_FALLBACK = /\b(stats|hp|damage|hero|troop|game|clash|synergy|best with|use with)\b/i;

function isGameTurn({ content = '', gameData = null, intent = null } = {}) {
  if (gameData) return true;
  if (intent === INTENTS.GAME) return true;
  return GAME_KEYWORD_FALLBACK.test(content);
}

module.exports = { isGameTurn, GAME_KEYWORD_FALLBACK };
